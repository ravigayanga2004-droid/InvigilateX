export type ExamRow = {
  id: string;
  title: string;
  description: string;
  instructions: string;
  status: string;
  courseId: string;
  course?: { name: string; code: string };
  durationSeconds: number;
  startAt: string;
  endAt: string;
  maxAttempts: number;
  passingScore: number;
  randomizeQuestions: boolean;
  randomizeOptions: boolean;
  showResultsImmediately: boolean;
  showCorrectAnswers: boolean;
  allowResume: boolean;
  requireFullscreen: boolean;
  settings?: { integrityEnabled: boolean };
  _count?: { questions: number; attempts: number };
  questions?: { questionId: string; points: string; question: QuestionRow }[];
};
